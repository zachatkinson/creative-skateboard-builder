/**
 * The builder's store, `creative-skateboard-builder`: private and locked, so nothing can come to depend on it (spec:
 * Upgrades and the public API). The server renders the page, and the same template re-renders from the view the
 * state route answers with (D-148). The store holds that view and whether a request is out; every word and address in
 * it is the server's, and the script carries none.
 *
 * - **A step's form** sends its fields to the route, the button pressed among them. Without the route, the form is
 *   sent as it would be without JavaScript.
 * - **A pick** is the shopper's own radio, painted by the browser at once; the route is asked for the same step with it
 *   once the shopper stops picking.
 * - **A link** on the builder (Back, a step done, Change, an error) asks the route for its address. A link opened in
 *   another tab or window is left to the browser.
 * - **Back and Forward** ask the route for the address the browser is now at.
 * - **After a step changes,** focus goes to what the shopper reads first: the error summary, the change panel's
 *   heading, or the step's heading; the page's title says the step (D-149). **After a pick,** the status region says
 *   the build and its total, once (spec: Keyboard and screen readers). **A move that stays on the step** (assembly,
 *   a filter) keeps focus on the control used and says the total; after Show more, focus goes to the first new card.
 * - **Add to cart** posts the build to the Store API, then tells the carts (`wc-blocks_added_to_cart`, on which the
 *   Mini-Cart refreshes) and says so; without the Store API, the form goes to WooCommerce's own handler (D-155).
 * - **Two events** on the builder's element, bubbling, for a shop's own analytics under its own consent (spec:
 *   Privacy): `cbuild:pick`, with the kit, the slot and the part, and `cbuild:added`, with the kit, its picks and
 *   assembly. They carry IDs alone.
 * - **The phone bar** never covers the control in focus: one the bar overlaps is scrolled clear of it (D-160).
 * - **Copy link** writes the build's shared link to the clipboard and says so. It is offered only where the browser
 *   has a clipboard to write to; the address is in the page as a field either way, and a refused copy selects it.
 * - **The board turns over** (#46). Each view says which side its step shows (the grip step, the top); the button by
 *   the board turns it, and from then on the side the shopper chose is kept on every view that can draw it. The
 *   picture and the phone bar show the same side, and the stylesheet turns the board only where motion is allowed.
 */
import { getConfig, getElement, store } from '@wordpress/interactivity';
import { fit, size } from './bar';
import { Navigator, type Move, type View } from './navigate';
import { add, body } from './cart';
import type { CbuildState } from '../types/state';

export const NAME = 'creative-skateboard-builder';

interface Config {
	cart: string;
	endpoint: string;
	page: number;
	locale: string;
	title: { before: string; after: string };
}

/**
 * The view as the store reads it: the fields schema/state.json describes for it, generated by `npm run types`. A field
 * the server stops sending fails the route's contract test; one the store reads unsaid is `unknown`, which tsc will
 * not let it use as a string, a number or a list.
 */
type Shown = View & NonNullable< CbuildState[ 'view' ] >;

interface State {
	view: Shown;
	pending: boolean;
	status: string;
	added: boolean;
	canCopy: boolean;
	canTurn: boolean;
	live: boolean;
	turning: boolean;
	/** The route's rate limit, in its words, while the step waits to be asked again; empty otherwise. */
	limited: string;
}

let navigator: Navigator | undefined;

/**
 * The side the shopper turned the board to with the button, once they have: it then holds over each step's own.
 */
let side: 'top' | 'under' | undefined;

/**
 * Show a view on the side the shopper chose, where it can draw it; a view whose board has no top shows its underside.
 *
 * @param view The view to be shown.
 */
function sided( view: Shown ): void {
	if ( view.picture && undefined !== side ) {
		view.picture.turned = view.picture.turnable && 'top' === side;
	}
}

/**
 * The builder's own element, as its init callback found it.
 */
let root: HTMLElement | null = null;

/**
 * Whether an add is on its way: a second press while it is would put a second build in the cart.
 */
let adding = false;

/**
 * What the shopper reads first after a step changes, by the template's classes.
 *
 * @param view The view now shown.
 */
function first( view: Shown ): string {
	if ( view.errors.shown ) {
		return '.cbuild-errors';
	}
	return view.isChanges ? '.cbuild-changes__heading' : '.cbuild__heading';
}

/**
 * Says a view: the status region after a pick; after a step, the page's title, and focus once the page shows it. A
 * move that stays on the step (assembly, a filter, Show more) is no step: focus stays on the control used and the
 * region says the total, and after Show more focus goes to the first new card (spec: Keyboard and screen readers).
 *
 * @param state   The store's state.
 * @param view    The view now shown.
 * @param history How the move treats history.
 * @param config  The page's config.
 * @param before  The view it takes the place of.
 */
function say(
	state: State,
	view: Shown,
	history: Move[ 'history' ],
	config: Partial< Config >,
	before: Shown
): void {
	if ( 'replace' === history ) {
		state.status = view.status;
		return;
	}
	const stays =
		! view.isChanges &&
		! before.isChanges &&
		! view.errors.shown &&
		view.step.slot === before.step.slot;
	if ( stays ) {
		const was = before.step.options ?? [];
		const now = view.step.options ?? [];
		const shown = was.length;
		// Show more keeps the list and adds to it. A width, a chip or a search that lists more is no Show more: focus
		// stays on the control used.
		const more =
			shown > 0 &&
			now.length > shown &&
			was.every(
				( option, at ) =>
					( option as { id?: unknown } ).id ===
					( now[ at ] as { id?: unknown } | undefined )?.id
			);
		// After Show more the region says how many it added, and the card focus goes to is read with it.
		state.status = more ? ( view.step.more?.added ?? '' ) : view.status;
		if ( more ) {
			window.requestAnimationFrame( () => {
				root?.querySelector< HTMLElement >(
					`.cbuild-cards > li:nth-child(${ shown + 1 }) input`
				)?.focus();
			} );
		}
		return;
	}
	// The change panel says how many parts changed; a step is read from its heading, so the region says nothing.
	state.status = view.isChanges ? view.status : '';
	const around = config.title ?? { before: '', after: '' };
	document.title = around.before + view.title + around.after;
	const target = first( view );
	// The page shows the new view once the Interactivity API has rendered it, before the next frame.
	window.requestAnimationFrame( () => {
		root?.querySelector< HTMLElement >( target )?.focus();
	} );
}

/**
 * How long after an add a cart drawer that opens on it may still take focus, in milliseconds. The Mini-Cart opens on
 * the add's event and moves focus into its drawer once it has drawn it, which may come after the builder's next
 * frame (Cowork's recheck, finding 10; D-183).
 */
export const SETTLE = 2000;

/**
 * Whether focus is somewhere a drawer or another part of the page took it: not the page itself, not in the builder,
 * and not an element the builder is inside, which a theme may focus on a click (Storefront's content, in WebKit).
 *
 * @param focused The element with focus.
 * @param page    The page.
 */
function taken( focused: Element | null, page: Document ): boolean {
	return (
		null !== focused &&
		focused !== page.body &&
		null !== root &&
		! root.contains( focused ) &&
		! focused.contains( root )
	);
}

/**
 * Say an add once, the same way whichever comes first, the builder's next frame or a cart drawer that opens on the
 * add and takes focus (Cowork's review, minor 10; recheck, finding 10). With no drawer, the notice takes focus and is
 * read, and the status says nothing more. Where a drawer has focus, or takes it within SETTLE, focus is left there
 * and the status says the add.
 *
 * @param state The store's state.
 * @param page  The page.
 */
function told( state: State, page: Document ): void {
	const announce = (): void => {
		state.status = state.view.review.added;
	};
	window.requestAnimationFrame( () => {
		if ( taken( page.activeElement, page ) ) {
			announce();
			return;
		}
		root?.querySelector< HTMLElement >( '.cbuild-review__added' )?.focus();
		const watch = ( event: FocusEvent ): void => {
			if ( taken( event.target as Element | null, page ) ) {
				stop();
				announce();
			}
		};
		const stop = (): void => {
			window.clearTimeout( timer );
			page.removeEventListener( 'focusin', watch );
		};
		const timer = window.setTimeout( stop, SETTLE );
		page.addEventListener( 'focusin', watch );
	} );
}

/**
 * Whether the browser is sending a form the store let go: its submit handlers then leave the event alone.
 */
let leaving = false;

/**
 * What the builder does without JavaScript's help, named so that a test can see it done.
 */
export const browser = {
	assign: ( url: string ): void => window.location.assign( url ),
	reload: (): void => window.location.reload(),
	/**
	 * Send a form as the browser would without JavaScript, the button pressed among its fields: the browser's own
	 * submit, which the store's handlers stand aside for, so no field is made to carry the button (no markup is
	 * built in the script).
	 *
	 * @param form      The form.
	 * @param submitter The button pressed, if any: sent only where it is the form's own.
	 */
	submit: ( form: HTMLFormElement, submitter?: HTMLElement | null ): void => {
		const own =
			( submitter instanceof HTMLButtonElement ||
				submitter instanceof HTMLInputElement ) &&
			submitter.form === form
				? submitter
				: undefined;
		leaving = true;
		try {
			form.requestSubmit( own );
		} finally {
			leaving = false;
		}
	},
};

/**
 * Show a change of view: crossed over with a view transition where the browser has one and the shopper allows
 * motion, at once otherwise (spec: Motion; D-161). The transition waits for the Interactivity API's render, which
 * runs on a microtask, before it takes the new picture; the stylesheet sets its timing.
 *
 * @param change What changes the view.
 */
function motion( change: () => void ): void {
	if (
		'function' !== typeof document.startViewTransition ||
		window.matchMedia?.( '(prefers-reduced-motion: reduce)' ).matches
	) {
		change();
		return;
	}
	document.startViewTransition( () => {
		change();
		return new Promise< void >( ( done ) => window.setTimeout( done ) );
	} );
}

/**
 * How many times the page is scrolled to bring a control back where it was after a view on the same step: the bar's
 * stuck and unstuck places take two; the third is spare.
 */
const SETTLE_PASSES = 3;

/**
 * Show a view on the same step with the control the shopper is on where it was on the screen: the one with focus in
 * the builder, or else the part picked on the step, as WebKit gives a pressed radio no focus. The first deck's answer
 * starts every later slot on its recommendation, so the picture comes in and the presets go above the step, and Next
 * moved by 166 pixels; WebKit drops a press that starts on a button and ends off it, so a Next pressed as the answer
 * came was lost (CI run 43520699158). The page is scrolled by what the view moved the control, once the Interactivity
 * API has drawn it and before the browser paints, as a browser's own scroll anchoring does where it has one (D-185).
 *
 * @param change What changes the view.
 */
function steady( change: () => void ): void {
	const focused = root?.ownerDocument.activeElement;
	const anchor =
		focused instanceof HTMLElement &&
		focused !== root &&
		root?.contains( focused )
			? focused
			: root?.querySelector< HTMLElement >(
					'.cbuild-step input[type="radio"]:checked'
				);
	const before = anchor?.getBoundingClientRect().top;
	change();
	if ( ! anchor || undefined === before ) {
		return;
	}
	window.requestAnimationFrame( () => {
		// A control in the phone bar moves as the bar does: stuck at the foot of the screen, then, once the scroll
		// brings the builder's end into view, at that end. So the scroll is measured again, a few times at most, until
		// the control is back; each pass lays the page out, and none paints (D-267).
		for ( let pass = 0; pass < SETTLE_PASSES; pass++ ) {
			const moved = anchor.isConnected
				? anchor.getBoundingClientRect().top - before
				: 0;
			if ( Math.abs( moved ) < 1 ) {
				return;
			}
			window.scrollBy( 0, moved );
		}
	} );
}

/**
 * Keep the bar's height on the page as its lines change, for the scroll padding that keeps focus clear of it (D-272).
 * A browser with no resize observer keeps the stylesheet's room for two rows.
 *
 * @param element The builder's element.
 */
function measure( element: HTMLElement ): void {
	const bar = element.querySelector( '.cbuild-bar' );
	size( element );
	if ( ! bar || 'function' !== typeof window.ResizeObserver ) {
		return;
	}
	new window.ResizeObserver( () => size( element ) ).observe( bar );
}

/**
 * Mark a pick in the store at once: the step's cards bind their radios' checked to it, so a card drawn again while the
 * route is asked would otherwise put the pick back as it was until the answer came (#47). The answer then says the
 * same, or what the server found instead.
 *
 * @param view  The view shown.
 * @param value The radio's value: a part's ID, or "0" for leaving the slot empty.
 */
function chosen( view: Shown, value: string ): void {
	const step = view.step as {
		options?: unknown;
		leave?: unknown;
	};
	if ( Array.isArray( step.options ) ) {
		for ( const option of step.options as unknown[] ) {
			if ( option && 'object' === typeof option ) {
				const card = option as { value?: unknown; checked?: boolean };
				card.checked = card.value === value;
			}
		}
	}
	if ( step.leave && 'object' === typeof step.leave ) {
		( step.leave as { checked?: boolean } ).checked = '0' === value;
	}
}

/**
 * The navigator, made on first use from the page's config.
 *
 * @param state The store's state.
 */
function nav( state: State ): Navigator {
	if ( undefined === navigator ) {
		const config = getConfig( NAME ) as Partial< Config >;
		navigator = new Navigator( {
			endpoint: String( config.endpoint ),
			page: Number( config.page ?? 0 ),
			locale: String( config.locale ?? '' ),
			fetch: ( input, init ) => window.fetch( input, init ),
			show: ( view, history ) => {
				const shown = view as Shown;
				// A pick that opens the change panel is a step: an entry of its own, which Back leaves for the step
				// the pick was made on, with focus on the panel's heading, as Next would have it (D-152).
				const turned =
					'replace' === history &&
					shown.isChanges &&
					! state.view.isChanges
						? 'push'
						: history;
				const before = state.view;
				sided( shown );
				// A side shown that was not is a turn the shopper sees, where motion is allowed; the same side ends the
				// last turn, so a board shown again later is not turned.
				state.turning =
					undefined !== shown.picture &&
					undefined !== before.picture &&
					shown.picture.turned !== before.picture.turned;
				const change = () => {
					state.view = shown;
					state.added = false;
					state.limited = '';
					say( state, shown, turned, config, before );
				};
				// Only a new step crosses over (spec: Motion): a transition takes the screen's taps while it
				// runs, so one for a view on the same step would lose a Next tapped straight after a pick.
				if (
					shown.step.slot !== before.step.slot ||
					shown.isChanges !== before.isChanges
				) {
					motion( change );
				} else {
					steady( change );
				}
				return turned;
			},
			pending: ( on ) => {
				state.pending = on;
			},
			limited: ( message ) => {
				state.limited = message;
				state.status = message;
			},
			push: ( url ) => window.history.pushState( null, '', url ),
			replace: ( url ) => window.history.replaceState( null, '', url ),
		} );
	}
	return navigator;
}

/**
 * Forget the navigator: for tests, which give each its own page.
 */
export function reset(): void {
	navigator = undefined;
	root = null;
	side = undefined;
}

/**
 * A form's fields as text, the button pressed among them.
 *
 * @param form      The form.
 * @param submitter The button pressed, if any.
 */
function fields(
	form: HTMLFormElement,
	submitter?: HTMLElement | null
): Array< [ string, string ] > {
	return [ ...new FormData( form, submitter ?? null ) ].filter(
		( field ): field is [ string, string ] => typeof field[ 1 ] === 'string'
	);
}

/**
 * Send a form as the browser would without JavaScript, the button pressed among its fields.
 *
 * @param form      The form.
 * @param submitter The button pressed, if any.
 */
/**
 * How long search waits after the last key, in milliseconds.
 */
const SEARCH_WAIT = 150;

/**
 * The search waiting to be sent.
 */
let typing: number | undefined;

/**
 * Lists the step again as its shelf's fields now ask: its search, chips and sort, on the step it is on. The
 * address is replaced, not pushed, so Back leaves the step rather than undoing each chip.
 *
 * @param form The step's form.
 */
function narrowed( form: HTMLFormElement ): void {
	nav( state ).go( {
		fields: [ ...fields( form ), [ 'cbuild[step]', state.view.step.slot ] ],
		history: 'replace',
		fallback: () => send( form ),
	} );
}

function send( form: HTMLFormElement, submitter?: HTMLElement | null ): void {
	browser.submit( form, submitter ?? null );
}

const { state } = store(
	NAME,
	{
		state: {
			pending: false,
			status: '',
			added: false,
			canCopy: false,
			canTurn: false,
			live: false,
			turning: false,
			limited: '',
		} as State,
		callbacks: {
			init(): void {
				root = getElement().ref;
				state.canCopy =
					'function' === typeof window.navigator.clipboard?.writeText;
				// The button turns the board in the page; without the script the step's own side is shown.
				state.canTurn = true;
				state.live = true;
				if ( root ) {
					fit( root );
					measure( root );
				}
			},
		},
		actions: {
			submit( event: SubmitEvent ): void {
				const form = getElement().ref;
				if ( leaving || ! ( form instanceof HTMLFormElement ) ) {
					return;
				}
				event.preventDefault();
				const move: Move = {
					fields: fields( form, event.submitter ),
					history: 'push',
					fallback: () => send( form, event.submitter ),
				};
				nav( state ).go( move );
			},
			narrow( event: Event ): void {
				const control = event.target;
				if (
					! (
						control instanceof HTMLInputElement ||
						control instanceof HTMLSelectElement
					) ||
					null === control.form
				) {
					return;
				}
				narrowed( control.form );
			},
			search( event: Event ): void {
				const input = event.target;
				if (
					! ( input instanceof HTMLInputElement ) ||
					null === input.form
				) {
					return;
				}
				const form = input.form;
				window.clearTimeout( typing );
				// 150 ms after the last key (SPEC-CONFIGURATOR, Search); the navigator drops an answer a later one overtakes.
				typing = window.setTimeout(
					() => narrowed( form ),
					SEARCH_WAIT
				);
			},
			pick( event: Event ): void {
				const input = event.target;
				if (
					! ( input instanceof HTMLInputElement ) ||
					'radio' !== input.type ||
					null === input.form
				) {
					return;
				}
				chosen( state.view, input.value );
				root?.dispatchEvent(
					new CustomEvent( 'cbuild:pick', {
						bubbles: true,
						detail: {
							kit: state.view.kit,
							slot: state.view.step.slot,
							part: Number( input.value ),
						},
					} )
				);
				nav( state ).pick( {
					fields: [
						...fields( input.form ),
						[ 'cbuild[step]', state.view.step.slot ],
					],
					history: 'replace',
					// The radio stays picked, and the form's Next sends it.
					fallback: () => undefined,
				} );
			},
			async add( event: SubmitEvent ): Promise< void > {
				const form = getElement().ref;
				if ( leaving || ! ( form instanceof HTMLFormElement ) ) {
					return;
				}
				event.preventDefault();
				if ( adding ) {
					return;
				}
				adding = true;
				state.status = '';
				const sent = fields( form, event.submitter );
				const config = getConfig( NAME ) as Partial< Config >;
				state.pending = true;
				const added = await add(
					{
						cart: String( config.cart ?? '' ),
						fetch: ( input, init ) => window.fetch( input, init ),
					},
					sent
				);
				state.pending = false;
				adding = false;
				if ( ! added ) {
					send( form, event.submitter );
					return;
				}
				const item = body( sent );
				// The Mini-Cart listens on the document, as for any product added (D-155).
				form.ownerDocument.body.dispatchEvent(
					new CustomEvent( 'wc-blocks_added_to_cart', {
						bubbles: true,
						cancelable: true,
					} )
				);
				root?.dispatchEvent(
					new CustomEvent( 'cbuild:added', {
						bubbles: true,
						detail: {
							kit: item.id,
							picks: item.cbuild.picks,
							assembly: item.cbuild.assembly ?? false,
						},
					} )
				);
				state.added = true;
				told( state, form.ownerDocument );
			},
			/**
			 * Show the top, or the underside again: the button by the board, its pressed state the side shown (#46).
			 * The shopper's side is kept from now on.
			 */
			turn(): void {
				const picture = state.view.picture;
				if ( ! picture?.turnable ) {
					return;
				}
				side = picture.turned ? 'under' : 'top';
				state.turning = true;
				picture.turned = ! picture.turned;
			},
			/**
			 * The screen changed: fit the phone bar into the theme again (D-163).
			 */
			fit(): void {
				if ( root ) {
					fit( root );
					size( root );
				}
			},
			reveal( event: FocusEvent ): void {
				const target = event.target;
				const bar = root?.querySelector< HTMLElement >( '.cbuild-bar' );
				if (
					! ( target instanceof HTMLElement ) ||
					! bar ||
					0 === bar.getClientRects().length ||
					bar.contains( target )
				) {
					return;
				}
				// A browser that scrolls a focused control only when it leaves the screen (Firefox) leaves it under the
				// bar; scrolling it into view honours the page's scroll padding, which clears the bar (D-160).
				if (
					target.getBoundingClientRect().bottom >
					bar.getBoundingClientRect().top
				) {
					target.scrollIntoView( { block: 'nearest' } );
				}
			},
			async copy(): Promise< void > {
				try {
					await window.navigator.clipboard.writeText(
						state.view.review.link
					);
					state.status = state.view.review.copied;
				} catch {
					// Refused, as a browser may without a secure page or the shopper's leave: the shopper copies it.
					const link = root?.querySelector< HTMLInputElement >(
						'.cbuild-share__link'
					);
					link?.focus();
					link?.select();
				}
			},
			follow( event: MouseEvent ): void {
				const link = getElement().ref;
				if (
					! ( link instanceof HTMLAnchorElement ) ||
					0 !== event.button ||
					event.metaKey ||
					event.ctrlKey ||
					event.shiftKey ||
					event.altKey
				) {
					return;
				}
				const url = new URL( link.href );
				if ( url.origin !== window.location.origin ) {
					return;
				}
				event.preventDefault();
				nav( state ).go( {
					fields: [ ...url.searchParams ],
					history: 'push',
					fallback: () => browser.assign( url.href ),
				} );
			},
			back(): void {
				nav( state ).go( {
					fields: [
						...new URLSearchParams( window.location.search ),
					],
					fallback: () => browser.reload(),
				} );
			},
		},
	},
	{ lock: true }
);
