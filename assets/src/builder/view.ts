/**
 * The control under a press, from the pointer going down to its coming up.
 */
let held: HTMLElement | null = null;

/**
 * Notes the control a press lands on. WebKit focuses no button a pointer presses, so the answer that arrives under the
 * press would otherwise be kept in place by what was focused before, and the button would move under the finger.
 *
 * @param event The pointer going down.
 */
function press( event: Event ): void {
	held =
		event.target instanceof Element
			? event.target.closest< HTMLElement >( 'button, a, summary, label' )
			: null;
}

/**
 * Forgets the press once the pointer comes up, or the browser takes it over.
 */
function release(): void {
	held = null;
}

/**
 * A mouse press on one of the builder's controls, noted from the moment the script runs, and whether a click reached
 * it (#80). Hydration takes a pressed control out of the page and puts it back, and a browser drops the click of a press
 * whose element left the page between down and up, so a press held while the regions hydrate would come to nothing.
 */
let early: { control: HTMLElement; clicked: boolean } | null = null;

/**
 * The builder's controls a press can land on.
 */
const CONTROLS =
	'.cbuild :is(button, a, summary, label, input[type="radio"], input[type="checkbox"], input[type="submit"])';

/**
 * Notes the control a mouse press goes down on, inside the builder.
 *
 * @param event The pointer going down.
 */
function pressEarly( event: PointerEvent ): void {
	// No control waits on a moment: a press ends every one at once (spec: Milestone 11).
	cut();
	// A mouse's main button alone: the pointer's up says whether it was a mouse's.
	const control =
		0 === event.button && event.target instanceof Element
			? event.target.closest< HTMLElement >( CONTROLS )
			: null;
	early = control ? { control, clicked: false } : null;
}

/**
 * Notes that the click of the press reached its control.
 *
 * @param event The click.
 */
function clickEarly( event: MouseEvent ): void {
	if (
		early &&
		event.target instanceof Node &&
		early.control.contains( event.target )
	) {
		early.clicked = true;
	}
}

/**
 * Once the press comes up over its control, gives it the click the browser dropped, if it did. The click comes after
 * the pointer's up in the same task, so this looks once it has had its turn. A label's click goes to its control.
 *
 * @param event The pointer coming up.
 */
function releaseEarly( event: PointerEvent ): void {
	const pressed = early;
	// A press taken up as the script started may have been a finger's, whose tap the browser never drops.
	if ( ! pressed || 'mouse' !== event.pointerType ) {
		early = null;
		return;
	}
	const over = document.elementFromPoint( event.clientX, event.clientY );
	window.setTimeout( () => {
		early = null;
		if (
			! pressed.clicked &&
			pressed.control.isConnected &&
			// Over nothing, `contains()` is false.
			pressed.control.contains( over )
		) {
			pressed.control.click();
		}
	} );
}

document.addEventListener( 'pointerdown', pressEarly, true );
document.addEventListener( 'click', clickEarly, true );
document.addEventListener( 'pointerup', releaseEarly, true );

/**
 * A press that went down before this script ran, so before the listener above, is taken up as one that went down
 * after (#120, D-363): while the button is down, the control and the elements around it are `:active`.
 */
const already = document.querySelector< HTMLElement >( CONTROLS + ':active' );
early = already ? { control: already, clicked: false } : null;

/**
 * Each panel the shopper scrolled before its builder was ready, and where they left it (#94). Hydrating a region takes
 * its `data-wp-each` items out and puts them back. WebKit lays the panel out in between, with its contents shorter, and
 * cuts its scroll back to the top; nothing puts it back. So, until the builder is ready, the panel is put back where
 * the shopper left it after each change inside it. A change ends its task before the next scroll event, so the note
 * is still the shopper's.
 */
const scrolled = new Map< Element, number >();

const keep = new MutationObserver( () => {
	scrolled.forEach( ( kept, panel ) => {
		panel.scrollTop = kept;
	} );
} );

/**
 * Notes where the shopper left a panel whose builder is not ready yet.
 *
 * @param event The scroll, listened for on the document, as a panel's own does not bubble.
 */
function scrollEarly( event: Event ): void {
	const panel = event.target;
	if (
		panel instanceof Element &&
		panel.matches( '.cbuild:not([data-ready]) .cbuild__body' )
	) {
		if ( ! scrolled.has( panel ) ) {
			keep.observe( panel, { childList: true, subtree: true } );
		}
		scrolled.set( panel, panel.scrollTop );
	}
}

/**
 * Lets a ready builder's panel scroll as the store moves it.
 *
 * @param builder The builder now ready.
 */
function scrollReady( builder: Element ): void {
	builder.querySelectorAll( '.cbuild__body' ).forEach( ( panel ) => {
		scrolled.delete( panel );
	} );
	if ( 0 === scrolled.size ) {
		keep.disconnect();
	}
}

document.addEventListener( 'scroll', scrollEarly, true );

/**
 * Keeps a press on a button inside an element the page can focus, the picture's figure among them, from focusing
 * that element: WebKit focuses no button a pointer presses but hands focus to the nearest such ancestor, and scrolls it
 * into view, which moved the button from under the pointer before the click landed. The click still fires.
 *
 * @param event The mouse going down, on the builder it is listened for on.
 */
function steadyPress( event: Event ): void {
	const builder = event.currentTarget as Element;
	const control = ( event.target as Element ).closest( 'button' );
	// A button cannot hold another, so the nearest such element that is no button is the button's own ancestor; it
	// counts only inside the builder, and a button the page focuses itself is left alone.
	const focusable = ':not(button)[tabindex="-1"]';
	const inside = builder.querySelectorAll< Element >(
		`${ focusable } button`
	);
	const within = [ ...inside ].some(
		( button ) =>
			button === control &&
			builder.contains( button.closest( focusable ) )
	);
	if ( within ) {
		event.preventDefault();
	}
}

/**
 * Whether an add is on its way: a second press while it is would put a second build in the cart.
 */
let adding = false;

/**
 * A smart swap's press (#135, D-397): the swap control pressed, by its ID, and whether the press was its Undo. After a
 * swap focus goes to the notice that says it, which holds Undo; after Undo, back to the control that made the swap.
 */
const swapPress: { from: string; undo: boolean; pressed: boolean } = {
	from: '',
	undo: false,
	pressed: false,
};

/**
 * What the shopper reads first after a step changes, by the template's classes.
 *
 * @param view The view now shown.
 */
function first( view: Shown ): string {
	if ( view.errors.shown ) {
		return '.cbuild-errors';
	}
	return view.isChanges ? '.cbuild-changes__heading' : '.cbuild__heading';
}

/**
 * Says a view: the status region after a pick; after a step, the page's title, and focus once the page shows it. A
 * move that stays on the step (assembly, a filter, Show more) is no step: focus stays on the control used and the
 * region says the total, and after Show more focus goes to the first new card (spec: Keyboard and screen readers).
 *
 * @param state   The store's state.
 * @param view    The view now shown.
 * @param history How the move treats history.
 * @param config  The page's config.
 * @param before  The view it takes the place of.
 */
function say(
	state: State,
	view: Shown,
	history: Move[ 'history' ],
	config: Partial< Config >,
	before: Shown
): void {
	if ( 'replace' === history ) {
		state.status = view.status;
		return;
	}
	const stays =
		! view.isChanges &&
		! before.isChanges &&
		! view.errors.shown &&
		view.step.slot === before.step.slot;
	// A swap stays on the step, and the control pressed may be gone: focus goes to the notice, which says the swap and
	// holds Undo, and after Undo back to the control that made it (#135, D-397). The region says the build and total.
	const swapped = swapPress.pressed;
	swapPress.pressed = false;
	if ( stays && swapped ) {
		state.status = view.status;
		const undone = swapPress.undo && ! view.swapped.shown;
		window.requestAnimationFrame( () => {
			const control = undone
				? root?.querySelector< HTMLElement >(
						`[id="${ swapPress.from }"]`
					)
				: null;
			( view.swapped.shown
				? root?.querySelector< HTMLElement >( '.cbuild-swapped' )
				: ( control ??
					root?.querySelector< HTMLElement >( first( view ) ) )
			)?.focus();
		} );
		return;
	}
	if ( stays ) {
		const was = before.step.options ?? [];
		// A view with no list lists no more than the one before.
		const now = view.step.options ?? was;
		const shown = was.length;
		// Show more keeps the list and adds to it. A width, a chip or a search that lists more is no Show more: focus
		// stays on the control used. Each card asked for is in the longer list.
		const more =
			shown > 0 &&
			now.length > shown &&
			was.every(
				( option, at ) =>
					( option as { id?: unknown } ).id ===
					( now[ at ] as { id?: unknown } ).id
			);
		// After Show more the region says how many it added, and the card focus goes to is read with it.
		state.status = more ? ( view.step.more?.added ?? '' ) : view.status;
		if ( more ) {
			window.requestAnimationFrame( () => {
				root?.querySelector< HTMLElement >(
					`.cbuild-cards > li:nth-child(${ shown + 1 }) input`
				)?.focus();
			} );
		}
		return;
	}
	// The change panel says how many parts changed; a step is read from its heading, so the region says nothing.
	state.status = view.isChanges ? view.status : '';
	const around = config.title ?? { before: '', after: '' };
	document.title = around.before + view.title + around.after;
	const target = first( view );
	// The page shows the new view once the Interactivity API has rendered it, before the next frame.
	window.requestAnimationFrame( () => {
		root?.querySelector< HTMLElement >( target )?.focus();
	} );
}

/**
 * How long after an add a cart drawer that opens on it may still take focus, in milliseconds. The Mini-Cart opens on
 * the add's event and moves focus into its drawer once it has drawn it, which may come after the builder's next
 * frame (Cowork's recheck, finding 10; D-183).
 */
export const SETTLE = 2000;

/**
 * Whether focus is somewhere a drawer or another part of the page took it: not in the builder, and not an element the
 * builder is inside, such as the page's body or what a theme may focus on a click (Storefront's content, in WebKit).
 *
 * @param focused The element with focus.
 */
function taken( focused: Element | null ): boolean {
	return (
		null !== focused &&
		null !== root &&
		! root.contains( focused ) &&
		! focused.contains( root )
	);
}

/**
 * Say an add once, the same way whichever comes first, the builder's next frame or a cart drawer that opens on the
 * add and takes focus (Cowork's review, minor 10; recheck, finding 10). With no drawer, the notice takes focus and is
 * read, and the status says nothing more. Where a drawer has focus, or takes it within SETTLE, focus is left there
 * and the status says the add.
 *
 * @param state The store's state.
 * @param page  The page.
 */
function told( state: State, page: Document ): void {
	const announce = (): void => {
		state.status = state.view.review.added;
	};
	window.requestAnimationFrame( () => {
		if ( taken( page.activeElement ) ) {
			announce();
			return;
		}
		root?.querySelector< HTMLElement >( '.cbuild-review__added' )?.focus();
		// Watched until a drawer takes focus or the add has settled, whichever comes first.
		const watching = new AbortController();
		page.addEventListener(
			'focusin',
			( event: FocusEvent ): void => {
				if ( taken( event.target as Element | null ) ) {
					watching.abort();
					announce();
				}
			},
			{ signal: watching.signal }
		);
		window.setTimeout( () => watching.abort(), SETTLE );
	} );
}

/**
 * Whether the browser is sending a form the store let go: its submit handlers then leave the event alone.
 */
let leaving = false;

/**
 * What the builder does without JavaScript's help, named so that a test can see it done.
 */
export const browser = {
	assign: ( url: string ): void => window.location.assign( url ),
	reload: window.location.reload.bind( window.location ),
	/**
	 * Send a form as the browser would without JavaScript, the button pressed among its fields: the browser's own
	 * submit, which the store's handlers stand aside for, so no field is made to carry the button (no markup is
	 * built in the script).
	 *
	 * @param form      The form.
	 * @param submitter The button pressed, if any: sent only where it is the form's own.
	 */
	submit: ( form: HTMLFormElement, submitter?: HTMLElement | null ): void => {
		const own =
			( submitter instanceof HTMLButtonElement ||
				submitter instanceof HTMLInputElement ) &&
			submitter.form === form
				? submitter
				: undefined;
		leaving = true;
		try {
			form.requestSubmit( own );
		} finally {
			leaving = false;
		}
	},
};

/**
 * Where a view is among the steps: the current step's place on the rail, or -1 with none.
 *
 * @param view The view.
 */
function railPlace( view: Shown ): number {
	const rail = ( view as { progress?: Array< { current?: boolean } > } )
		.progress;
	return ( rail ?? [] ).findIndex( ( step ) => true === step.current );
}

/**
 * Show a new step: crossed over with a view transition, the panel sliding the way the shopper is going, or faded where
 * moments only fade (D-256); at once where the browser has none. The transition waits for the Interactivity API's
 * render, which runs on a microtask, before it takes the new picture; the stylesheet sets its timing.
 *
 * @param change What changes the view.
 * @param before The view before.
 * @param after  The view now.
 */
function motion( change: () => void, before: Shown, after: Shown ): void {
	// A step drawn with a part already picked shows it as it is: the card settles at a pick alone.
	root?.removeAttribute( 'data-picked' );
	cross( change, railPlace( after ) >= railPlace( before ), calm( root ) );
}

/**
 * The board's element on the stage that shows the side now shown.
 *
 * @param turned Whether the top is shown.
 */
function board( turned: boolean ): Element | null {
	return (
		root?.querySelector(
			turned
				? '.cbuild-picture .cbuild-board--top'
				: '.cbuild-picture .cbuild-board:not(.cbuild-board--top)'
		) ?? null
	);
}

/**
 * The board turns over like a card, to the side now shown (spec: Milestone 11, Show the top).
 *
 * @param toTop Whether the top is now shown.
 */
function turnOver( toTop: boolean ): void {
	const shown = board( toTop );
	if ( shown ) {
		play(
			shown,
			'turn',
			[ { transform: 'scaleX(0.1)' }, { transform: 'none' } ],
			calm( root )
		);
	}
}

/**
 * Turn the board to a side, from the buttons by it (#46, F28): the side the shopper chose is kept until the step
 * changes (F27, #127). The side already shown, or a board with no top, is left as it is.
 *
 * @param toTop Whether the top is to be shown.
 */
function turnTo( toTop: boolean ): void {
	const picture = state.view.picture;
	if ( ! picture?.turnable || picture.turned === toTop ) {
		return;
	}
	top = toTop;
	state.turning = true;
	picture.turned = toTop;
	window.requestAnimationFrame( () => turnOver( toTop ) );
}

/**
 * Whether a view takes a part off the stage that the last one had.
 *
 * @param before The view before.
 * @param after  The view now.
 */
function removes( before: Shown, after: Shown ): boolean {
	const now = new Set(
		( after.picture?.items ?? [] ).map( ( item ) => item.key )
	);
	return ( before.picture?.items ?? [] ).some(
		( item ) => ! now.has( item.key )
	);
}

/**
 * Play what a new view shows on the stage, once it is drawn: each part new to the board or swapped, the grip on its
 * top, the photos closing over a part removed, and the board turning to a side shown that was not.
 *
 * @param before The view before.
 * @param after  The view now.
 * @param was    Where the stage's photos were, where a part was removed.
 */
function moments(
	before: Shown,
	after: Shown,
	was: Map< Element, DOMRect > | undefined
): void {
	const quiet = calm( root );
	// The side shown alone: the top has a deck and wheels of its own, keyed as the underside's are.
	const upper = true === after.picture?.turned;
	const side = upper ? 'top' : 'board';
	const then =
		before.picture?.turned === after.picture?.turned
			? ( before.picture?.[ side ]?.layers ?? [] )
			: ( after.picture?.[ side ]?.layers ?? [] );
	const now = after.picture?.[ side ]?.layers ?? [];
	build( board( upper ), then, now, quiet );
	// The part picked, outlined on the board for the eye (#138, D-413).
	outline( board( upper ), then, now, quiet );
	if ( was ) {
		close( was, quiet );
	}
	if ( state.turning ) {
		turnOver( true === after.picture?.turned );
	}
}

/**
 * The total counts from the old amount to the new, each frame in the bar, and ends on the server's string; the
 * estimate under it fades in when it changes (spec: Milestone 11, Price changes; D-257). The status region says the
 * total once, as before: the bar's amount is hidden from screen readers.
 *
 * @param before The view before.
 * @param after  The view now, just shown.
 */
function priced( before: Shown, after: Shown ): void {
	const quiet = calm( root );
	if ( before.money && after.money && after.bar ) {
		const bar = after.bar;
		count(
			before.money.amount,
			after.money.amount,
			bar.amount,
			after.money.currency as unknown as Currency,
			( text ) => {
				state.view.bar!.amount = text;
			},
			quiet
		);
	}
	const estimate = root?.querySelector( '.cbuild-bar__estimate' );
	const was = ( before.bar as { estimate?: string } | undefined )?.estimate;
	const now = ( after.bar as { estimate?: string } | undefined )?.estimate;
	if ( estimate && was !== now ) {
		play(
			estimate,
			'total',
			[ { opacity: 0 }, { opacity: 1 } ],
			quiet,
			0,
			'none'
		);
	}
}

/**
 * How many times the page is scrolled to bring a control back where it was after a view on the same step: the bar's
 * stuck and unstuck places take two; the third is spare.
 */
const SETTLE_PASSES = 3;

/**
 * Show a view on the same step with the control the shopper is on where it was on the screen: the one with focus in
 * the builder, or else the part picked on the step, as WebKit gives a pressed radio no focus. The first deck's answer
 * starts every later slot on its recommendation, so the picture comes in and the presets go above the step, and Next
 * moved by 166 pixels; WebKit drops a press that starts on a button and ends off it, so a Next pressed as the answer
 * came was lost (CI run 43520699158). The page is scrolled by what the view moved the control, once the Interactivity
 * API has drawn it and before the browser paints, as a browser's own scroll anchoring does where it has one (D-185).
 *
 * @param change What changes the view.
 */
function steady( change: () => void ): void {
	// With no builder found, there is nothing on it to keep in place.
	const builder = root;
	if ( ! builder ) {
		change();
		return;
	}
	const focused = builder.ownerDocument.activeElement;
	const anchor =
		held ??
		( focused instanceof HTMLElement &&
		focused !== builder &&
		builder.contains( focused )
			? focused
			: builder.querySelector< HTMLElement >(
					'.cbuild-step input[type="radio"]:checked'
				) );
	const before = anchor?.getBoundingClientRect().top ?? 0;
	// The view that answers a width folded at its press leaves the widths as they are: the press closed them, so they
	// are open only where the shopper pressed Change before the answer came. Read before the change, since the press's
	// own fold sets it.
	const kept = pressFolded;
	pressFolded = false;
	change();
	window.requestAnimationFrame( () => {
		// Once a width is chosen the widths fold behind its line after every answer. Change opens them natively, and
		// the server's `asking` stays false throughout, so the bound `open` never changes and would leave them open.
		builder
			.querySelectorAll< HTMLDetailsElement >(
				'details.cbuild-width__pick'
			)
			.forEach( ( fold ) => {
				const line =
					fold.querySelector< HTMLElement >( ':scope > summary' );
				if ( line && ! ( kept && fold.open ) ) {
					fold.open = true === line.hidden;
				}
			} );
	} );
	if ( ! anchor ) {
		return;
	}
	window.requestAnimationFrame( () => {
		// A control the view folds away, as a width once chosen is, hands focus to its fold's summary: the line that
		// now says the width, with Change (the spec reviewer's M10 minor M1).
		const fold =
			anchor === focused ? anchor.closest( 'details:not([open])' ) : null;
		const summary =
			fold?.querySelector< HTMLElement >( ':scope > summary' );
		if ( summary && ! summary.hidden ) {
			summary.focus();
		}
		// A control in the phone bar moves as the bar does: stuck at the foot of the screen, then, once the scroll
		// brings the builder's end into view, at that end. So the scroll is measured again, a few times at most, until
		// the control is back; each pass lays the page out, and none paints (D-267).
		for ( let pass = 0; pass < SETTLE_PASSES; pass++ ) {
			const moved = anchor.isConnected
				? anchor.getBoundingClientRect().top - before
				: 0;
			if ( Math.abs( moved ) < 1 ) {
				return;
			}
			window.scrollBy( 0, moved );
		}
	} );
}

/**
 * Keep the bar's height on the page as its lines change, for the scroll padding that keeps focus clear of it (D-272).
 * A browser with no resize observer keeps the stylesheet's room for two rows.
 *
 * @param element The builder's element.
 */
function measure( element: HTMLElement ): void {
	size( element );
	stage( element );
	if ( 'function' !== typeof window.ResizeObserver ) {
		return;
	}
	const bar = element.querySelector( '.cbuild-bar' );
	const shown = element.querySelector( '.cbuild__stage' );
	if ( bar ) {
		// The control in focus keeps it while the bar or a line over it grows: the limit's line comes 10 s after a
		// press, over a card picked with Space just above the bar, and nothing else scrolls it clear (D-383).
		const sized = new window.ResizeObserver( () => {
			size( element );
			clear( element.ownerDocument.activeElement );
		} );
		sized.observe( bar );
		// What a press of the dimmed Next says, and the limit's line, sit over the bar, outside its box: their
		// heights count as the bar's (D-383).
		bar.querySelectorAll(
			'.cbuild-bar__missing, .cbuild__limited'
		).forEach( ( said ) => sized.observe( said ) );
	}
	// The stage sticks on top, or stands beside the panel, as the builder's width changes its size.
	if ( shown ) {
		new window.ResizeObserver( () => stage( element ) ).observe( shown );
	}
}

/**
 * How many frames a row is measured in at most: the button's words change with how many it holds, so its width is
 * measured again once it says them, and only ever taken as wider, so the row settles.
 */
const ROW_PASSES = 3;

/**
 * The frame the row waits for.
 */
let frame = 0;

/**
 * The chips each row was last laid out for, so a view that changes none of them leaves the row as it is.
 */
const laid = new WeakMap< Element, string >();

/**
 * What a row of chips is laid out for: each chip's value, count and whether it is chosen. A view that changes any of
 * them lays the row out again.
 *
 * @param group The chips' group.
 */
function marked( group: Chipped[ 'group' ] ): string {
	return ( group?.inputs ?? [] )
		.map( ( chip ) => [ chip.value, chip.count, chip.checked ].join( ':' ) )
		.join( ' ' );
}

/**
 * Each row's watcher for a change of size, its own or a chip's.
 */
const rowWatchers = new WeakMap< Element, ResizeObserver >();

/**
 * Lay out a row of brand chips (#98): in the next frame, the values that don't fit beside "N more", measured again
 * until they settle.
 *
 * @param options The group's row of chips.
 * @param least   The button's width at least.
 * @param passes  How many frames it may still take.
 */
function lay( options: HTMLElement, least = 0, passes = ROW_PASSES ): void {
	window.cancelAnimationFrame( frame );
	frame = window.requestAnimationFrame( () => {
		const found = shut( options, least );
		if ( found.values.join( '\n' ) === state.shut.join( '\n' ) ) {
			state.laid = laid.get( options ) ?? '';
			return;
		}
		state.shut = found.values;
		if ( passes > 1 ) {
			lay( options, found.button, passes - 1 );
			return;
		}
		state.laid = laid.get( options ) ?? '';
	} );
}

/**
 * Whether the shopper opened the rest of the step's chips.
 */
function opened(): boolean {
	return '' !== state.opened && state.opened === state.view.step.slot;
}

/**
 * Mark a pick in the store at once: the step's cards bind their radios' checked to it, so a card drawn again while the
 * route is asked would otherwise put the pick back as it was until the answer came (#47). The answer then says the
 * same, or what the server found instead.
 *
 * @param view  The view shown.
 * @param value The radio's value: a part's ID, a size's (which is a part's ID too), or "0" for leaving the slot empty.
 */
function chosen( view: Shown, value: string ): void {
	const step = view.step as {
		options?: unknown;
		leave?: unknown;
	};
	if ( Array.isArray( step.options ) ) {
		for ( const option of step.options as unknown[] ) {
			if ( option instanceof Object ) {
				const card = option as {
					value?: unknown;
					checked?: boolean;
					sizeGroup?: {
						inputs?: { value?: unknown; checked?: boolean }[];
					};
				};
				// A size picked after its card is a part of the card's look: the card stays picked (D-279).
				const sizes = card.sizeGroup?.inputs ?? [];
				let sized = false;
				for ( const input of sizes ) {
					input.checked = input.value === value;
					sized = sized || input.checked;
				}
				card.checked = card.value === value || sized;
			}
		}
	}
	if ( step.leave instanceof Object ) {
		( step.leave as { checked?: boolean } ).checked = '0' === value;
	}
	// A radio of the step is checked, a part or No risers, so Next sends a pick: lit before the route answers, as the
	// card is, so that a Next pressed straight after the pick goes on (#100). The answer then says the same.
	if ( view.bar ) {
		view.bar.next.ready = true;
	}
}

/**
 * Make at a pick what the store already knows its answer will show, so that the answer, which on a real host comes
 * after the 500 ms CLS leaves out after a press, moves nothing on the page (F20, #118; D-356). The answer then says
 * the same, or what the server found instead.
 *
 * - The ready builds are offered at the start alone: a build begun is the shopper's own.
 * - The deck step's line ("Start with a width") goes once its deck is chosen.
 * - Once the step has a part picked, each card says its price against it under its own (D-249): the line is kept,
 *   empty, for the server's words. Left empty, as by No risers, the step says no such prices.
 * - A step recommends a part only while it has none picked.
 * - The bar keeps the estimate's line once the build has a part, so the estimate the answer brings moves nothing.
 *
 * @param view  The view shown.
 * @param value The radio's value: a part's ID, or "0" for leaving the slot empty.
 */
function foretell( view: Shown, value: string ): void {
	const known = view as {
		presets?: { shown?: boolean };
		bar?: { started?: boolean };
		step: { slot: string; hasLead?: boolean; options?: unknown };
	};
	if ( known.presets ) {
		known.presets.shown = false;
	}
	const part = '0' !== value;
	// The build has a part: the bar keeps the line for the estimate its answer brings (D-374).
	if ( known.bar && part ) {
		known.bar.started = true;
	}
	if ( 'deck' === known.step.slot && part ) {
		known.step.hasLead = false;
	}
	if ( Array.isArray( known.step.options ) ) {
		for ( const option of known.step.options as unknown[] ) {
			if ( option instanceof Object ) {
				const card = option as {
					hasDelta?: boolean;
					recommended?: boolean;
				};
				card.hasDelta = part;
				// A step recommends a part only while it has none picked.
				card.recommended = true === card.recommended && ! part;
			}
		}
	}
}

/**
 * Fold the width question to its chosen line at the press of a width, as its answer will: the widths behind the line
 * that says the one pressed, with Change, and the step's list, which the answer fills, under it (F20, #118; D-356).
 * The ready builds wait for the answer out of sight, in their place (`data-folded`), so the decks it brings take it
 * rather than push them down, and the page under the builder does not move twice. The step's lead, the guided
 * start and a smart swap's notice go at the press too, as the answer takes them (F30, D-405). Null where the press is
 * no width the step asks for.
 *
 * @param view   The view shown.
 * @param button The button pressed.
 */
function folding(
	view: Shown,
	button: HTMLElement | null | undefined
): ( () => void ) | null {
	const known = view as {
		guide?: { shown?: boolean; asked?: boolean };
		swapped?: { shown?: boolean };
		step: {
			hasLead?: boolean;
			more?: { count?: string };
			shelf?: {
				width?: {
					name?: string;
					asking?: boolean;
					chosen?: string;
					options: {
						value: string;
						text: string;
						pressed: string;
					}[];
				};
			};
		};
	};
	const width = known.step.shelf?.width;
	if (
		! button ||
		true !== width?.asking ||
		button.getAttribute( 'name' ) !== width.name
	) {
		return null;
	}
	const value = button.getAttribute( 'value' );
	const pressed = width.options.find( ( option ) => option.value === value );
	if ( ! pressed ) {
		return null;
	}
	return () => {
		const said = width.chosen ?? '';
		const was = width.options.map( ( option ) => option.pressed );
		const more = known.step.more;
		const counted = more?.count ?? '';
		const step = known.step;
		const led = true === step.hasLead;
		const guide = known.guide;
		const guided = true === guide?.shown;
		const notice = known.swapped;
		const noticed = true === notice?.shown;
		// A press the rate limit or the store's limit stops asks the question again, with the width it pressed (D-364).
		unfold = () => {
			pressFolded = false;
			width.asking = true;
			width.chosen = said;
			width.options.forEach( ( option, at ) => {
				option.pressed = was[ at ] ?? 'false';
			} );
			if ( more ) {
				more.count = counted;
			}
			step.hasLead = led;
			if ( guide ) {
				guide.shown = guided;
			}
			if ( notice ) {
				notice.shown = noticed;
			}
			window.requestAnimationFrame( () => button.focus() );
		};
		width.asking = false;
		width.chosen = pressed.text;
		for ( const option of width.options ) {
			option.pressed = option === pressed ? 'true' : 'false';
		}
		root?.setAttribute( 'data-folded', '' );
		pressFolded = true;
		// The step's lead and the guided start go with a width, as the answer will take them (D-360, D-404): gone at
		// the press, within the 500 ms CLS leaves out, they leave the late answer nothing to move up (F30, D-405).
		// Builds the guide was asked for stay, as the answer keeps them.
		step.hasLead = false;
		if ( guide && true !== guide.asked ) {
			guide.shown = false;
		}
		// A smart swap's notice lasts until the next move, which this is, so the answer takes it too (#135, D-397).
		if ( notice ) {
			notice.shown = false;
		}
		// "Showing 0 of 0" until the answer lists the decks: a line the cards would push down.
		if ( more ) {
			more.count = '';
		}
	};
}

/** Undo a width's fold made at its press, until the answer comes. */
let unfold: ( () => void ) | undefined;

/** Whether the next view shown answers a width folded at its press, whose widths the shopper may have opened since. */
let pressFolded = false;

/** The pick whose board is being drawn at its press, until a view is shown, so one decoded late draws over nothing. */
let swapping: object | undefined;

/**
 * Draw the pressed deck's board at the press, from its card's image, which pointing at the card fetched (F23, #121;
 * D-357), once it is decoded, so the board never shows half drawn. The rest of the picture keeps the cue that its
 * answer is on its way. The answer then confirms the deck, or brings the change panel or a refusal, and the board is
 * drawn as it says: put back, where the server refused the deck. The server still decides fit and price; this shows.
 *
 * @param view  The view shown.
 * @param value The radio's value.
 */
function swap( view: Shown, value: string ): void {
	const now = {};
	swapping = now;
	// Anything in the list that is not a card is no deck.
	const options = ( view.step.options ?? [] ) as Array< {
		id?: number;
		preload?: Preload;
	} | null >;
	const preload = options.find(
		( option ) => String( option?.id ) === value
	)?.preload;
	const layers = view.picture?.board?.layers ?? [];
	const deck = layers.find( ( layer ) => 'deck-1' === layer.key );
	if (
		! preload?.shown ||
		true === view.picture?.turned ||
		! deck ||
		deck.src === preload.src
	) {
		return;
	}
	const image = fetchBoard( preload );
	void image?.decode().then(
		() => {
			if ( now !== swapping ) {
				return;
			}
			const before = layers.map( ( layer ) => ( { ...layer } ) );
			deck.src = preload.src;
			deck.sizes = preload.sizes;
			for ( const source of deck.sources ?? [] ) {
				source.srcset =
					'image/avif' === source.type ? preload.avif : preload.webp;
				source.sizes = preload.sizes;
			}
			root?.setAttribute( 'data-swapped', '' );
			window.requestAnimationFrame( () => {
				build( board( false ), before, layers, calm( root ) );
				outline( board( false ), before, layers, calm( root ) );
			} );
		},
		// Not decoded: the old board stays whole until the answer.
		() => undefined
	);
}

/**
 * Ask ahead for the step's Next once it is lit, so the next step can be shown at the press of it (F20, #118; D-355):
 * on a real host its answer comes after the 500 ms CLS leaves out after a press, and the new step it brings would be
 * counted as layout shift. Its fields are the form's, sent by the bar's Next, as a press of it sends them. Not on a
 * view a search, a chip or Sort brought: a shopper narrowing the shelf asks often, and the route counts each request.
 */
function foresee(): void {
	const view = state.view;
	const next = view.bar?.next as
		| { ready?: boolean; onStep?: boolean; name?: string; value?: string }
		| undefined;
	const form = root?.querySelector< HTMLFormElement >( 'form.cbuild-step' );
	if (
		true !== next?.ready ||
		true !== next.onStep ||
		view.isChanges ||
		! form
	) {
		return;
	}
	const button = [ ...form.elements ].find(
		( control ): control is HTMLButtonElement =>
			control instanceof HTMLButtonElement &&
			control.classList.contains( 'cbuild-bar__next' ) &&
			control.name === next.name &&
			control.value === next.value
	);
	if ( button ) {
		nav( state ).prefetch( fields( form, button ) );
	}
}

/** Whether the last move narrowed the shelf: its answer asks nothing ahead. */
let narrowing: boolean | undefined;

/**
 * How long, in ms, a pointer rests on a deck's card before its board's image is fetched: one passing over the shelf
 * fetches nothing (D-308).
 */
export const INTENT = 80;

/** How long after a press on a card the pick it makes counts as pressed, and is asked at once. */
const PRESSED = 1000;

/** The pointer resting on a card, waiting out INTENT. */
let resting: number | undefined;

/** When a card was last pressed. */
let pressed = Number.NEGATIVE_INFINITY;

/** Whether a pick waits for its answer: only that wait says the picture is being drawn. */
let picking = false;

/** The board images fetched, by their files, each once. */
const boards = new Map< string, HTMLImageElement >();

/** A deck's board image, as its card carries it and as a view's deck layer gives it. */
interface Preload {
	shown: boolean;
	src: string;
	avif: string;
	webp: string;
	sizes: string;
}

/**
 * Fetch a board's image in the type the stage draws, once, as the stage will ask for it: the same files and sizes,
 * so the browser chooses the same one and has it in its cache. Where nothing is drawn yet, WebP, which every browser
 * the builder supports reads.
 *
 * @param preload The image.
 */
function fetchBoard( preload: Preload | undefined ): HTMLImageElement | null {
	if ( ! preload?.shown || '' === preload.src ) {
		return null;
	}
	const drawn =
		( root ?? document ).querySelector< HTMLImageElement >(
			'.cbuild-picture .cbuild-board:not(.cbuild-board--top) .cbuild-board__image'
		)?.currentSrc ?? '';
	const srcset =
		( drawn.endsWith( '.avif' ) && preload.avif ) || preload.webp;
	const key = srcset || preload.src;
	let image = boards.get( key );
	if ( undefined === image ) {
		image = new Image();
		image.decoding = 'async';
		if ( '' !== srcset ) {
			// Sizes before the files, so the browser chooses once.
			image.sizes = preload.sizes;
			image.srcset = srcset;
		}
		image.src = preload.src;
		boards.set( key, image );
	}
	return image;
}

/**
 * The board image of the deck whose card the element is, as the step's options carry it.
 */
function pointedAt(): Preload | undefined {
	const value =
		getElement().ref?.querySelector< HTMLInputElement >(
			'input[type=radio]'
		)?.value;
	const options = ( state.view.step.options ?? [] ) as Array< {
		id?: number;
		preload?: Preload;
	} >;
	return options.find( ( option ) => String( option.id ) === value )?.preload;
}

/**
 * Ready a view before it is shown: where it draws another deck, that deck's board image fetched and decoded, so the
 * old board stays whole until the new one takes its place (D-308). The navigator holds it at most HOLD.
 *
 * @param view The view to show.
 */
function ready( view: View ): Promise< void > | null {
	const deck = ( view as Shown ).picture?.board?.layers.find(
		( layer ) => 'deck-1' === layer.key
	);
	const now = state.view.picture?.board?.layers.find(
		( layer ) => 'deck-1' === layer.key
	);
	if ( undefined === deck?.src || '' === deck.src || deck.src === now?.src ) {
		return null;
	}
	const of = ( type: string ): string =>
		deck.sources?.find( ( source ) => type === source.type )?.srcset ?? '';
	const image = fetchBoard( {
		shown: true,
		src: deck.src,
		avif: of( 'image/avif' ),
		webp: of( 'image/webp' ),
		sizes: deck.sizes ?? '',
	} );
	return image?.decode() ?? null;
}

/**
 * The navigator, made on first use from the page's config.
 *
 * @param state The store's state.
 */
function nav( state: State ): Navigator {
	if ( undefined === navigator ) {
		const config = getConfig( NAME ) as Partial< Config >;
		navigator = new Navigator( {
			endpoint: String( config.endpoint ),
			page: Number( config.page ?? 0 ),
			locale: String( config.locale ?? '' ),
			late: String( config.late ?? '' ),
			fetch: ( input, init ) => window.fetch( input, init ),
			show: ( view, history ) => {
				const shown = view as Shown;
				// A pick that opens the change panel is a step: an entry of its own, which Back leaves for the step
				// the pick was made on, with focus on the panel's heading, as Next would have it (D-152).
				const turned =
					'replace' === history &&
					shown.isChanges &&
					! state.view.isChanges
						? 'push'
						: history;
				const before = state.view;
				// A new answer ends whatever moment the last one started.
				cut();
				const moved =
					shown.step.slot !== before.step.slot ||
					shown.isChanges !== before.isChanges;
				// A new step opens on its own side: the shopper's turn was the last step's (F27, #127).
				if ( moved ) {
					top = undefined;
				}
				sided( shown );
				// A side shown that was not is a turn the shopper sees, where motion is allowed; the same side ends the
				// last turn, so a board shown again later is not turned.
				state.turning =
					undefined !== shown.picture &&
					undefined !== before.picture &&
					shown.picture.turned !== before.picture.turned;
				// Where a part comes off the stage, its photos are measured before, to close the gap after.
				const was =
					root && removes( before, shown )
						? measured( [
								...root.querySelectorAll(
									'.cbuild-picture .cbuild-picture__item'
								),
							] )
						: undefined;
				// A deck drawn at its press is the view's to confirm or put back from now (D-357).
				swapping = undefined;
				unfold = undefined;
				const ahead = ! narrowing;
				const change = () => {
					state.view = shown;
					state.added = false;
					state.limited = '';
					state.missing = '';
					say( state, shown, turned, config, before );
					priced( before, shown );
					window.requestAnimationFrame( () => {
						moments( before, shown, was );
						if ( ahead ) {
							foresee();
						}
						// The Interactivity API has drawn the view by this frame.
						rendered( root, shown );
					} );
				};
				// Only a new step crosses over (spec: Motion): a transition takes the screen's taps while it
				// runs, so one for a view on the same step would lose a Next tapped straight after a pick.
				if ( moved ) {
					motion( change, before, shown );
				} else {
					steady( change );
				}
				return turned;
			},
			pending: ( on ) => {
				state.pending = on;
				state.drawing = on && picking;
				if ( ! on ) {
					picking = false;
					// The answer is in, or failed: what the press foretold gives way to it.
					root?.removeAttribute( 'data-folded' );
					root?.removeAttribute( 'data-swapped' );
				}
			},
			settle: ( view ) => ready( view ),
			limited: ( message ) => {
				unfold?.();
				unfold = undefined;
				state.limited = message;
				state.status = message;
			},
			push: ( url ) => window.history.pushState( null, '', url ),
			replace: ( url ) => window.history.replaceState( null, '', url ),
		} );
	}
	return navigator;
}

/**
 * The picture's renderer (SPEC: Ready for 3D): the 2D board's, which the template draws, until the 3D view opens.
 */
let renderer: Renderer = flat;

/** Each press of View in 3D, so a press that closes it while its script is on its way leaves it closed. */
let opening = 0;

/**
 * The scene the server measured for a view, where the kit offers 3D and a deck is picked.
 *
 * @param view The view.
 */
function scened( view: Shown ): Scene | null {
	return ( view as Shown & { scene?: Scene | null } ).scene ?? null;
}

/**
 * Close the 3D view, giving everything it holds back, and show the board.
 *
 * @param state The store's state.
 */
function flatten( state: State ): void {
	opening++;
	renderer.close();
	renderer = flat;
	state.three.open = false;
	state.three.loading = false;
}

/**
 * The 3D view could not be shown, or stopped: the board comes back, the message shows under it, and the status
 * region says it once, in the server's words.
 *
 * @param state The store's state.
 */
function fell( state: State ): void {
	flatten( state );
	state.three.failed = true;
	state.status =
		root?.querySelector( '.cbuild-3d__failed' )?.textContent?.trim() ?? '';
}

/**
 * Open the 3D view: its script, loaded now and not before, drawing the view's scene on the canvas the server
 * rendered. No WebGL 2, a lost context or anything thrown goes back to the board.
 *
 * @param state The store's state.
 */
async function rise( state: State ): Promise< void > {
	const canvas =
		root?.querySelector< HTMLCanvasElement >( '.cbuild-3d__canvas' );
	if ( ! canvas ) {
		return;
	}
	const ticket = ++opening;
	state.three.loading = true;
	state.three.failed = false;
	try {
		const { open } = await import(
			/* webpackChunkName: "builder/three" */ './three/index'
		);
		if ( ticket !== opening ) {
			return;
		}
		state.three.open = true;
		renderer = open( {
			canvas,
			reduced: () => calm( root ),
			failed: () => fell( state ),
		} );
		renderer.show(
			scened( state.view ),
			true === state.view.picture?.turned
		);
	} catch {
		fell( state );
		return;
	}
	state.three.loading = false;
}

/**
 * Forget the navigator: for tests, which give each its own page.
 */
export function reset(): void {
	navigator = undefined;
	root = null;
	held = null;
	top = undefined;
	boards.clear();
	renderer.close();
	renderer = flat;
	opening = 0;
	pressed = Number.NEGATIVE_INFINITY;
	picking = false;
	narrowing = undefined;
	swapping = undefined;
	window.clearTimeout( resting );
}

/**
 * A form's fields as text, the button pressed among them.
 *
 * @param form      The form.
 * @param submitter The button pressed, if any.
 */
function fields(
	form: HTMLFormElement,
	submitter?: HTMLElement | null
): Array< [ string, string ] > {
	return [ ...new FormData( form, submitter ?? null ) ].filter(
		( field ): field is [ string, string ] => typeof field[ 1 ] === 'string'
	);
}

/**
 * How long search waits after the last key, in milliseconds.
 */
const SEARCH_WAIT = 150;

/**
 * The search waiting to be sent.
 */
let typing: number | undefined;

/**
 * Lists the step again as its shelf's fields now ask: its search, chips and sort, on the step it is on. The
 * address is replaced, not pushed, so Back leaves the step rather than undoing each chip.
 *
 * @param form The step's form.
 */
function narrowed( form: HTMLFormElement ): void {
	narrowing = true;
	nav( state ).go( {
		fields: [ ...fields( form ), [ 'cbuild[step]', state.view.step.slot ] ],
		history: 'replace',
		fallback: () => send( form ),
	} );
}

/**
 * Send a form as the browser would without JavaScript, the button pressed among its fields.
 *
 * @param form      The form.
 * @param submitter The button pressed, if any.
 */
function send( form: HTMLFormElement, submitter?: HTMLElement | null ): void {
	browser.submit( form, submitter ?? null );
}

/**
 * The top of what the bar covers: its own top, or the top of what it says over itself while it says something, what
 * a press of the dimmed Next says (#100) and the limit's line (D-383), as `size()` counts them for the page's scroll
 * padding (D-388). Empty or hidden, each has no height.
 *
 * @param bar The bar.
 */
function covers( bar: HTMLElement ): number {
	let at = bar.getBoundingClientRect().top;
	for ( const line of bar.querySelectorAll(
		'.cbuild-bar__missing, .cbuild__limited'
	) ) {
		const said = line.getBoundingClientRect();
		if ( said.height > 0 ) {
			at = Math.min( at, said.top );
		}
	}
	return at;
}

/**
 * Keep a focused control clear of the phone bar at the foot and the stage that sticks on top: the builder's focusin.
 *
 * @param event The focus that came in.
 */
function reveal( event: FocusEvent ): void {
	clear( event.target );
}

/**
 * Bring a control clear of the bar and the stage where either covers it: the one focus comes to, or the one that keeps
 * it while the bar grows or says something over itself (D-383).
 *
 * @param target The control.
 */
function clear( target: EventTarget | null ): void {
	if ( ! ( target instanceof HTMLElement ) || ! root?.contains( target ) ) {
		return;
	}
	const bar = root?.querySelector< HTMLElement >( '.cbuild-bar' );
	const shown = root?.querySelector< HTMLElement >( '.cbuild__stage' );
	const place = target.getBoundingClientRect();
	// A browser that scrolls a focused control only when it leaves the screen (Firefox, WebKit) leaves it under
	// the bar at the foot, or the stage that sticks on top; scrolling it into view honours the page's scroll
	// padding, which clears both (D-160; the auditor's M10 review, 1).
	const under =
		!! bar &&
		0 !== bar.getClientRects().length &&
		! bar.contains( target ) &&
		place.bottom > covers( bar );
	const behind =
		!! shown &&
		! shown.contains( target ) &&
		'sticky' === window.getComputedStyle( shown ).position &&
		place.top < shown.getBoundingClientRect().bottom;
	if ( under || behind ) {
		target.scrollIntoView( { block: 'nearest' } );
	}
}

const { state } = store(
	NAME,
	{
		state: {
			pending: false,
			drawing: false,
			status: '',
			added: false,
			canCopy: false,
			canTurn: false,
			live: false,
			turning: false,
			limited: '',
			folded: false,
			three: { open: false, loading: false, failed: false },
			missing: '',
			get dimmed(): boolean {
				return state.live && false === state.view.bar?.next.ready;
			},
			shut: [] as string[],
			opened: '',
			get past(): boolean {
				const { group, chip } = getContext< Chipped >();
				return (
					true === group?.more?.shown &&
					! opened() &&
					state.shut.includes( chip?.value ?? '' )
				);
			},
			get rests(): boolean {
				return (
					state.live &&
					true === getContext< Chipped >().group?.more?.shown
				);
			},
			get idle(): boolean {
				return 0 === state.shut.length;
			},
			laid: '',
			get laying(): boolean {
				const { group } = getContext< Chipped >();
				return (
					true === group?.more?.shown &&
					! opened() &&
					marked( group ) !== state.laid
				);
			},
			get open(): boolean {
				return opened();
			},
			get rest(): string {
				const more = getContext< Chipped >().group?.more;
				return opened()
					? ( more?.fewer ?? '' )
					: ( more?.texts?.[ Math.max( state.shut.length, 1 ) - 1 ] ??
							'' );
			},
		} as State,
		callbacks: {
			/**
			 * Lay out the brand chips in one row (#98), once hydrated, again when a view changes a chip, what it
			 * counts or what is chosen, and again when the row's size changes.
			 */
			row(): void {
				const { group } = getContext< Chipped >();
				const options = getElement().ref;
				if ( true !== group?.more?.shown || ! options ) {
					return;
				}
				// Read here, so a view that changes the chips runs this again.
				const marks = marked( group );
				if ( 'function' === typeof window.ResizeObserver ) {
					let watcher = rowWatchers.get( options );
					if ( ! watcher ) {
						watcher = new window.ResizeObserver( () =>
							lay( options )
						);
						rowWatchers.set( options, watcher );
						watcher.observe( options );
					}
					// Each chip as well, as when a web font arrives after the first measure; a view may bring new
					// chips, and observing one twice does nothing.
					for ( const chip of options.querySelectorAll(
						'.cbuild-chips__chip'
					) ) {
						watcher.observe( chip );
					}
				}
				if ( marks !== laid.get( options ) ) {
					laid.set( options, marks );
					lay( options );
				}
			},
			/**
			 * Draw each view's scene in the 3D view, once it is open, on its step's side (1.4.0, #139): a part changed
			 * swaps that part alone. The board's renderer has nothing to draw.
			 */
			scene(): void {
				renderer.show(
					scened( state.view ),
					true === state.view.picture?.turned
				);
			},
			/**
			 * Say on the builder whether an answer is awaited: its root is no region, so no directive binds it (D-296).
			 */
			busy(): void {
				const busy = String( state.pending );
				getElement()
					.ref?.closest( '.cbuild' )
					?.setAttribute( 'aria-busy', busy );
			},
			/**
			 * Mark the builder ready: run by the bar, its last region, so every piece has been hydrated before it
			 * (D-296). A press before then goes as the page would send it without the script.
			 */
			ready(): void {
				const builder = getElement().ref?.closest( '.cbuild' );
				if ( builder ) {
					builder.setAttribute( 'data-ready', '' );
					scrollReady( builder );
				}
				rendered( builder ?? null, state.view );
			},
			init(): void {
				// The builder's pieces are regions of their own, each hydrated in its own task (D-296), so the root
				// is the builder around the one this runs in.
				root =
					getElement().ref?.closest< HTMLElement >( '.cbuild' ) ??
					null;
				state.canCopy =
					'function' === typeof window.navigator.clipboard?.writeText;
				// The button turns the board in the page; without the script the step's own side is shown.
				state.canTurn = true;
				state.live = true;
				// On a phone the cards come first, and the filters wait behind their button (spec: Phone).
				state.folded = true;
				if ( root ) {
					fit( root );
					measure( root );
					root.addEventListener( 'focusin', reveal );
					root.addEventListener( 'pointerdown', press );
					root.addEventListener( 'mousedown', steadyPress );
					root.ownerDocument.addEventListener( 'pointerup', release );
					root.ownerDocument.addEventListener(
						'pointercancel',
						release
					);
				}
			},
		},
		actions: {
			submit( event: SubmitEvent ): void {
				const form = getElement().ref;
				if ( leaving || ! ( form instanceof HTMLFormElement ) ) {
					return;
				}
				event.preventDefault();
				// The step's Next pressed before the step has a pick says what is missing beside it, and sends nothing:
				// the error summary the server would answer with is for a page with no script (#100).
				if (
					event.submitter?.hasAttribute( 'aria-disabled' ) &&
					state.dimmed
				) {
					const missing = state.view.bar?.next.missing ?? '';
					state.missing = missing;
					// Heard once, in the builder's one status region; the words beside Next are its description. A second
					// press would set the words the region already holds, which a polite region does not say again: it is
					// emptied, and the words come back on the next frame unless something else has spoken.
					if ( state.status !== missing ) {
						state.status = missing;
						return;
					}
					state.status = '';
					window.requestAnimationFrame( () => {
						if ( '' === state.status ) {
							state.status = missing;
						}
					} );
					return;
				}
				// A search still waiting from the keys typed would go out after this and undo it, as Clear search was.
				// The form carries the box as it is, so nothing typed is lost.
				window.clearTimeout( typing );
				narrowing = false;
				// The width pressed folds behind its line, which takes focus from it as an answer's fold does.
				const fold = folding( state.view, event.submitter );
				if ( fold ) {
					steady( fold );
				}
				const move: Move = {
					fields: fields( form, event.submitter ),
					history: 'push',
					fallback: () => send( form, event.submitter ),
				};
				nav( state ).go( move );
			},
			narrow( event: Event ): void {
				const control = event.target;
				if (
					! (
						control instanceof HTMLInputElement ||
						control instanceof HTMLSelectElement
					) ||
					null === control.form
				) {
					return;
				}
				narrowed( control.form );
			},
			search( event: Event ): void {
				const input = event.target;
				if (
					! ( input instanceof HTMLInputElement ) ||
					null === input.form
				) {
					return;
				}
				const form = input.form;
				window.clearTimeout( typing );
				nav( state ).drop();
				// 150 ms after the last key (SPEC-CONFIGURATOR, Search); the navigator drops an answer a later one overtakes.
				typing = window.setTimeout(
					() => narrowed( form ),
					SEARCH_WAIT
				);
			},
			/**
			 * A pointer on a deck's card: resting on it, its board's image is fetched after INTENT; pressing it, at
			 * once, and the pick it makes is asked at once (D-308).
			 *
			 * @param event The pointer's event.
			 */
			point( event: PointerEvent ): void {
				window.clearTimeout( resting );
				const preload = pointedAt();
				if ( 'pointerdown' === event.type ) {
					pressed = performance.now();
					fetchBoard( preload );
					return;
				}
				resting = window.setTimeout(
					() => fetchBoard( preload ),
					INTENT
				);
			},
			/**
			 * The pointer has left the card before INTENT: nothing is fetched.
			 */
			leave(): void {
				window.clearTimeout( resting );
			},
			pick( event: Event ): void {
				const input = event.target;
				if (
					! ( input instanceof HTMLInputElement ) ||
					'radio' !== input.type ||
					null === input.form
				) {
					return;
				}
				cut();
				narrowing = false;
				chosen( state.view, input.value );
				foretell( state.view, input.value );
				// The stylesheet settles the card picked under this mark alone, never as a page or a step is drawn. The
				// phone's stage does not stick at this mark: it starts to stick at the answer (D-303, D-356).
				root?.setAttribute( 'data-picked', '' );
				swap( state.view, input.value );
				state.missing = '';
				root?.dispatchEvent(
					new CustomEvent( 'cbuild:pick', {
						bubbles: true,
						detail: {
							kit: state.view.kit,
							slot: state.view.step.slot,
							part: Number( input.value ),
						},
					} )
				);
				picking = true;
				// A press, a tap or a click is one pick, asked at once; the arrows wait for the last (D-308).
				const byPress = performance.now() - pressed < PRESSED;
				pressed = Number.NEGATIVE_INFINITY;
				nav( state ).pick(
					{
						fields: [
							...fields( input.form ),
							[ 'cbuild[step]', state.view.step.slot ],
						],
						history: 'replace',
						// The radio stays picked, and the form's Next sends it.
						fallback: () => undefined,
					},
					byPress
				);
			},
			async add( event: SubmitEvent ): Promise< void > {
				const form = getElement().ref;
				if ( leaving || ! ( form instanceof HTMLFormElement ) ) {
					return;
				}
				event.preventDefault();
				if ( adding ) {
					return;
				}
				adding = true;
				state.status = '';
				const sent = fields( form, event.submitter );
				const config = getConfig( NAME ) as Partial< Config >;
				state.pending = true;
				const added = await add(
					{
						cart: String( config.cart ?? '' ),
						fetch: ( input, init ) => window.fetch( input, init ),
					},
					sent
				);
				state.pending = false;
				adding = false;
				if ( ! added ) {
					send( form, event.submitter );
					return;
				}
				const item = body( sent );
				// The Mini-Cart listens on the document, as for any product added (D-155).
				form.ownerDocument.body.dispatchEvent(
					new CustomEvent( 'wc-blocks_added_to_cart', {
						bubbles: true,
						cancelable: true,
					} )
				);
				root?.dispatchEvent(
					new CustomEvent( 'cbuild:added', {
						bubbles: true,
						detail: {
							kit: item.id,
							picks: item.cbuild.picks,
							assembly: item.cbuild.assembly ?? false,
						},
					} )
				);
				state.added = true;
				told( state, form.ownerDocument );
				carted(
					board( true === state.view.picture?.turned ),
					calm( root )
				);
			},
			/**
			 * Open or fold the phone's filters behind their button.
			 */
			filters(): void {
				state.folded = ! state.folded;
			},
			/**
			 * Open the brand chips past the row in place, with focus on the first of them, or fold them again (#98).
			 */
			more(): void {
				if ( opened() ) {
					state.opened = '';
					return;
				}
				const shown = getElement()
					.ref?.closest( '.cbuild-chips__options' )
					?.querySelector< HTMLElement >(
						'.cbuild-chips__chip--past .cbuild-chips__control'
					);
				state.opened = state.view.step.slot;
				// The chip shows once the Interactivity API has rendered the open row, before the next frame.
				window.requestAnimationFrame( () => shown?.focus() );
			},
			/**
			 * Show the underside: its button by the board, pressed while it is shown (F28, #128).
			 */
			under(): void {
				turnTo( false );
			},
			/**
			 * Show the top: its button by the board, pressed while it is shown (F28, #128).
			 */
			over(): void {
				turnTo( true );
			},
			/**
			 * View in 3D (1.4.0, #139): open the 3D view, or close it and show the board again. A press while its
			 * script is on its way closes it as well.
			 */
			async three(): Promise< void > {
				if ( state.three.open || state.three.loading ) {
					flatten( state );
					return;
				}
				await rise( state );
			},
			/**
			 * One of the 3D view's camera buttons: the button's value names where it sends the camera.
			 */
			look(): void {
				const where = placeOf(
					( getElement().ref as HTMLButtonElement | null )?.value
				);
				if ( where ) {
					renderer.look( where );
				}
			},
			/**
			 * The screen changed: fit the phone bar into the theme again (D-163).
			 */
			fit(): void {
				if ( root ) {
					fit( root );
					size( root );
				}
			},
			reveal( event: FocusEvent ): void {
				reveal( event );
			},
			async copy(): Promise< void > {
				try {
					await window.navigator.clipboard.writeText(
						state.view.review.link
					);
					state.status = state.view.review.copied;
				} catch {
					// Refused, as a browser may without a secure page or the shopper's leave: the shopper copies it.
					const link = root?.querySelector< HTMLInputElement >(
						'.cbuild-share__link'
					);
					link?.focus();
					link?.select();
				}
			},
			follow( event: MouseEvent ): void {
				const link = getElement().ref;
				if (
					! ( link instanceof HTMLAnchorElement ) ||
					0 !== event.button ||
					event.metaKey ||
					event.ctrlKey ||
					event.shiftKey ||
					event.altKey
				) {
					return;
				}
				const url = new URL( link.href );
				if ( url.origin !== window.location.origin ) {
					return;
				}
				event.preventDefault();
				narrowing = false;
				// A smart swap or its Undo, for where focus goes after it (#135, D-397).
				swapPress.pressed =
					link.classList.contains( 'cbuild-swap' ) ||
					link.classList.contains( 'cbuild-swapped__undo' );
				swapPress.undo = link.classList.contains(
					'cbuild-swapped__undo'
				);
				if ( link.classList.contains( 'cbuild-swap' ) ) {
					swapPress.from = link.id;
				}
				nav( state ).go( {
					fields: [ ...url.searchParams ],
					history: 'push',
					fallback: () => browser.assign( url.href ),
				} );
			},
			back(): void {
				narrowing = false;
				nav( state ).go( {
					fields: [
						...new URLSearchParams( window.location.search ),
					],
					fallback: () => browser.reload(),
				} );
			},
		},
	},
	{ lock: true }
);
